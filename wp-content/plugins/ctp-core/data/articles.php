Masonry in Chicago does not fail because it gets cold. It fails because it cannot make up its mind.

## The freeze-thaw cycle

Brick and mortar are porous. They absorb water, hold it, and release it as the wall dries. That is normal and the wall is designed for it.

The problem is what happens when absorbed water freezes. Water expands by about nine percent when it turns to ice, and inside a pore in a mortar joint, that expansion has nowhere to go. It pushes outward against the material around it.

One cycle does nothing measurable. What does the damage is repetition. Every freeze widens the pore slightly. Every thaw lets more water in than before. Over enough cycles the material fatigues, loses cohesion, and starts crumbling.

## Why our climate is worse than colder ones

This is the counterintuitive part. Somewhere genuinely cold, where the temperature drops in November and stays below freezing until March, masonry can do relatively well. Everything freezes once and stays frozen.

Chicago does something worse. We cross the freezing point constantly. A February week here can easily run 20 degrees overnight and 40 in the afternoon, five days in a row. That is five full freeze-thaw cycles in a week, each one absorbing meltwater during the day and freezing it at night.

Depending on the year, a wall here can go through eighty or more freeze-thaw cycles in a single winter. That cumulative count, not the low temperature, is what drives mortar to fail here in forty to sixty years.

## Why the south and west walls go first

They get the most sun, which means they thaw more often. A north wall in January may stay frozen for a week at a time. A south wall in the same week thaws every afternoon and refreezes every night.

More cycles, faster failure. This is why we so often find one or two elevations needing work while the others are fine, and why paying to repoint all four walls is frequently unnecessary.

## What road salt adds

Salt makes it worse in two ways. It gets into the masonry and crystallizes as it dries, and crystallizing salt exerts pressure inside pores much the way ice does. It also lowers the freezing point of the water in the wall, which means more cycling at temperatures that would otherwise be stable.

This is why steps, stoops and the bottom few courses of a wall near a driveway or sidewalk almost always look worse than the wall above them.

## What it means practically

**Mortar failing at forty to sixty years is normal here.** It is not a sign that something was done badly. Mortar is designed to be the sacrificial element.

**Keeping water out is the whole game.** Every repair that matters is really about reducing how much water gets into the masonry: repointing, sealant, flashing, crowns, weep holes, grading, downspouts.

**Sealing the wall shut is the wrong instinct.** A film-forming sealer stops the wall drying out and traps the water already in it. The goal is a wall that absorbs less and still breathes.

**Timing of repairs matters.** Fresh mortar needs to be above about 40 degrees to cure properly. Work done in marginal conditions in late autumn can fail its first winter. Any mason who offers to repoint in December is telling you something about their standards.

## The one thing worth doing this year

Walk your downspouts. Water discharging against the foundation is the single most common avoidable source of saturation in a masonry wall, and extending a downspout costs almost nothing compared to what repointing a soaked wall costs.
