There is one mistake in residential masonry that does more damage than all the others put together, and almost nobody notices it happening, because it takes about a decade to show up.

It is using mortar that is harder than the brick.

## How a brick wall is supposed to work

A masonry wall is not rigid. It expands and contracts with temperature, takes up and releases moisture, and settles slightly over time. All that movement has to go somewhere.

In a properly built wall, it goes into the mortar. Mortar is deliberately made weaker than the brick around it, so that when something has to give, it is the joint. That is why mortar is called the sacrificial element. Repointing a wall every forty or fifty years is not a failure of the system, it is the system working as designed.

## What modern mortar changed

Before roughly 1930, mortar around Chicago was lime-based: soft, flexible, slow-setting, and considerably weaker than the brick.

Modern mortar is Portland cement-based. It is strong, it sets fast, it is easy to work with, and it comes in a bag. For new construction with modern hard-fired brick, it is entirely appropriate.

On a hundred-year-old wall it is a serious problem, because it is harder than the brick it is holding together.

## What happens next

The wall keeps moving, because walls do. But now the mortar will not yield. So the movement is taken by the next weakest element, which is the century-old brick.

The stress concentrates at the edges of the joints, which is exactly where you start seeing brick faces crack and pop off.

At the same time, the hard mortar traps moisture. Lime mortar is permeable and lets a wall dry out through the joints. Portland mortar does not, so water that gets in has to leave through the brick face, taking salts with it and freezing there in winter.

Both mechanisms attack the brick. The joints, meanwhile, look immaculate, which is part of why the problem is so often misdiagnosed.

## How to tell if it has happened to your house

**Spalling right at the joint edges.** Brick faces cracking and lifting in a band along the mortar lines, rather than randomly across the face.

**Joints that look too good.** Crisp, gray, hard-looking joints on an otherwise old wall. If the mortar looks newer and harder than everything around it, it probably is.

**A repointing job in the last ten to twenty-five years.** Worth asking the previous owner or checking permit records if you can.

**The scratch test, in reverse.** On a prewar wall, the mortar should be a little softer than the brick. If the joint is noticeably harder than the brick face beside it, that is backwards.

## What the right mortar looks like

For a prewar Chicago home, that usually means a lime-rich mix. Type O or Type K rather than the Type N or Type S that comes out of the bag by default, sometimes with a genuine lime putty mix for the oldest and softest work.

The right mix is determined by the brick, not by preference. A mason working on an older home should be able to tell you what they are using and why, and should be testing it against the existing brick rather than reaching for whatever is on the truck.

## What to do if it has already been done

Unfortunately there is no cheap remedy. The hard mortar has to come out, which is slow and has to be done carefully because grinding hard mortar out of soft brick risks damaging the brick further. Spalled brick has to be replaced. Then the wall is repointed in a compatible mix.

It costs considerably more than the original repointing did. Which is the real argument for asking about mortar before the work rather than after it.

## The question to ask

When you get a quote on an older home, ask one thing: "What mortar type are you using, and how did you decide?"

If the answer is specific and mentions the age of the brick, you are in good hands. If the answer is vague, or is simply the name of a bag, keep looking.
