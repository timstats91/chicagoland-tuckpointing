Spalling is when the hard outer face of a brick flakes, crumbles or pops off, leaving the soft interior exposed. Once it starts, that brick absorbs water considerably faster than it used to, so it accelerates.

It is a symptom, not a disease. Replace the brick without finding the cause and you will be replacing it again.

## Cause one: failed mortar joints

The most common by a wide margin. Open joints let water into the wall. The water saturates the brick from behind, freezes, and blows the face off from the inside.

The tell is location: spalling clustered below or beside obviously failing joints, usually on the elevations that take weather.

Fix the joints and the spalling stops spreading.

## Cause two: mortar that is too hard

This one is less obvious and it is entirely self-inflicted.

Older brick, particularly anything laid before about 1930, is softer and more porous than modern brick, and it was laid with soft lime-based mortar. The system works because the mortar is the weakest element: as the wall expands and contracts, the mortar takes the movement.

Repoint that wall with modern Portland-heavy mortar and you invert the relationship. Now the mortar is harder than the brick. The wall still moves, but the brick is now the softest thing in it, so the brick takes the stress and the faces spall off at the joint edges.

The tell is distinctive: spalling concentrated right at the edges of joints, on a wall that was repointed sometime in the last ten or twenty years, often with joints that look suspiciously gray and hard.

There is no fixing this cheaply. The brick has to be replaced and the wall repointed properly, in the right mortar.

## Cause three: a water source you can see

Walk the wall and look for where water is being delivered to it:

- A downspout discharging against the foundation
- A gutter overflowing at a specific corner every storm
- A rusting lintel above a window, which both leaks and expands
- A patio, walk or driveway pitched toward the house
- A hose bib or dryer vent with failed sealant around it
- Grade that slopes toward the wall rather than away

Spalling concentrated in one vertical stripe or one corner almost always has a specific water source above it.

These are frequently the cheapest fixes on the whole list. Extending a downspout costs very little.

## Cause four: previous sandblasting

Brick has a hard fired outer skin from the kiln, and that skin is what resists water. Sandblasting removes it.

A great many Chicago-area buildings were blasted in the 1970s and 80s, when it was a common way to clean masonry. Those walls have been absorbing water at an elevated rate ever since, and they spall far faster than they should.

The tell is uniform, widespread surface deterioration across a whole elevation rather than clustering, often with an oddly rough, matte texture.

There is no undoing it. What helps is keeping water out by every other means: sound joints, good flashing, a breathable water repellent.

## What to do about it

**Find the cause first.** Any contractor who quotes brick replacement without telling you why the brick failed has skipped the important half.

**Fix the water path.** Joints, lintels, flashing, downspouts, grading.

**Then replace the brick.** Matched for size, color and texture. Common Chicago brick is still available, and salvage yards cover most older styles.

**Do not paint it.** It is tempting, and it is one of the worst things you can do to a spalling wall. Paint traps moisture inside brick that is already saturating too easily, and removing it later is expensive and risky.

**Do not seal it with a film-forming product either.** Same problem. A breathable siloxane repellent is fine; anything that forms a skin is not.

## When it is urgent

Isolated spalling on a few bricks is worth addressing but not an emergency. Spalling across an entire elevation, spalling that has gone deep enough to expose the full brick depth, or spalling combined with any movement in the wall means getting someone out now, because at that point the wall is losing structural material rather than just looking bad.
