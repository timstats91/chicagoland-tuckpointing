## What a chimney is up against

It stands above the roof with no shelter, exposed on four sides. It takes wind-driven rain, full sun, and the complete freeze-thaw cycle. And it gets attacked from the inside as well, because combustion pushes warm, moist, mildly acidic air up through the structure, where it condenses against cold masonry.

That is why chimneys usually fail first, often decades ahead of the rest of the house.

## Repair territory

If the following describes your chimney, you are almost certainly looking at repair rather than rebuilding:

- The stack is plumb and the brick below the top few courses is solid
- The mortar joints are largely intact when tested
- The crown is cracked or was only ever a thin mortar wash
- The flashing is rusted, lifted, or has been patched with roof tar
- There is no cap, or the cap is damaged

That set of problems, which is extremely common, gets solved with a new poured crown, new step and counter flashing, a cap, and repointing of the top courses. It is a one or two day job.

## Rebuild territory

These point the other way:

- The stack visibly leans or has a bow in it
- Mortar has failed throughout the exposed section, not just at the top
- Brick has spalled across multiple faces and courses
- Brick has actually fallen, or you have found pieces in the yard or gutters
- The chimney has separated from the house at the roofline
- Previous repointing is now failing again

If mortar has gone throughout the above-roofline section, repointing it is putting good money after bad, because the brick around those joints has usually deteriorated too.

## The honest middle ground

A lot of chimneys sit between the two: the top four or five courses are gone, the rest is sound. The right answer there is a partial rebuild, taking it down to solid masonry and rebuilding from that point with a proper crown.

A contractor who quotes a full rebuild on every chimney is not assessing, they are selling.

