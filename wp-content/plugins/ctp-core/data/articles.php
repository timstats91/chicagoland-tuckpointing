You do not need a mason to tell you whether your mortar is failing. You need about ten minutes, a screwdriver, and some idea of what you are looking at. Here is how to check.

## Start with the screwdriver test

This is the one that tells you the most. Take an ordinary flathead screwdriver or even a house key and drag it firmly along a mortar joint on the south or west side of the house.

Sound mortar resists. You might scratch it, but you will not dig into it.

Failing mortar gives way. The screwdriver sinks in, or the joint gives up a small shower of sand. If you can gouge a quarter inch out of a joint without much effort, that joint is done, and the joints around it are probably not far behind.

Do this in a few places, because mortar does not fail uniformly. Check high and low, and check the walls that take the weather.

## Look for sand at the base of the wall

Walk the perimeter and look at the ground right against the foundation, or at the top of a windowsill below a brick wall. Fine sandy grit collecting there means mortar is actively breaking down above it.

It is easy to miss because it looks like ordinary dirt. It is not. It is your mortar.

## Check the joint depth

Stand back and look at the wall in raking light, ideally early or late in the day when the sun is low. Sound joints sit close to the brick face. As mortar erodes, the joints recess, and in low light the wall develops a noticeably shadowed, pitted texture.

If some areas read deeper than others, those are the areas that have gone.

## Look for gaps and cracks

Obvious, but worth being systematic about. You are looking for:

- Hairline cracks running along the joints
- Sections where mortar is simply missing
- Joints that have separated from the brick on one side
- Stair-step cracking, which follows the joints diagonally up the wall

Stair-step cracking is a different problem from ordinary mortar wear. It usually points to settlement or to a rusting lintel rather than to age, and it is worth having looked at.

## Push on the brick

Find a spot where the joints look bad and press firmly on individual bricks. They should not move at all. Any rocking, shifting or give means the brick has lost its bond, and that is past the point where repointing alone will fix it.

## Check inside

Go down to the basement or into a room on an exterior wall after a good rain and look for:

- Damp patches on the inside face of an exterior wall
- White chalky deposits on interior masonry, which is efflorescence
- Peeling paint on an exterior wall
- A musty smell that comes back after rain

Any of these means water is getting through the wall, and failed mortar joints are the most common route.

## What the answers mean

**If the screwdriver test passes everywhere and you see no gaps**, you are fine. Check again in a couple of years.

**If one or two elevations fail but the rest are solid**, that is normal and it is good news. South and west walls take the worst of the weather and fail first. You may only need those walls done.

**If joints are failing and you also have spalling brick**, the repointing is now urgent, because the water that is getting in is already damaging the brick itself, and brick is far more expensive to replace than mortar is.

**If brick is moving or the wall is bowing**, stop testing and get someone out. That is beyond tuckpointing.

## A note on age

If your house is more than about forty years old and has never been repointed, the mortar is probably due regardless of what any single test shows. Mortar in the Chicago freeze-thaw climate has a service life of roughly forty to sixty years, and that is the whole point of it: mortar is designed to be the sacrificial element so that the brick is not.
